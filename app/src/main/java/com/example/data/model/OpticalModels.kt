@Keep
@IgnoreExtraProperties
data class Product(
  @DocumentId val id: String = "",
  val name: String = "",
  val brand: String = "",
  val sku: String = "",
  val category: String = "",
  val price: Double = 0.0,
  val discountPercent: Long = 0L,
  val description: String = "",
  val frameMaterial: String = "",
  val frameColour: String = "",
  val frameShape: String = "",
  val frameSize: String = "",
  val lensType: String = "",
  val stockCount: Long = 0L,
  val popularityScore: Long = 0L,
  val featured: Boolean = false,
  val bestSeller: Boolean = false,
  val newArrival: Boolean = false,
  val specialOffer: Boolean = false,
  val imageKey: String = "img_frames_optical",
  val imageUri: String? = null,
  val galleryKeys: List<String> = listOf("img_frames_optical"),
  val seoSlug: String = "",
  val createdAt: Timestamp? = null,
  val updatedAt: Timestamp? = null,
) {
  val finalPrice: Double
    get() = if (discountPercent > 0) price * (1.0 - discountPercent / 100.0) else price

  val inStock: Boolean
    get() = stockCount > 0L
}

